-- DDL: the relational model of the equipment-rental shop (lesson steps 2 and 4).
-- Run order: 001_schema.sql, 002_seed.sql, migrations/001_exclusion_constraint.sql, then 003_queries.sql and
-- 004_constraint_demo.sql (make db applies the first three; make queries and make demo run the others).
-- The tables are the lesson's step-2 design. The rule that makes a double booking impossible is step 4's change
-- and lives in the migration, so the lesson's "before" and "after" can both be run.

CREATE TABLE customers (
    customer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL CHECK (name <> '')
);

CREATE TABLE items (
    item_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text          NOT NULL CHECK (name <> ''),
    daily_rate numeric(8, 2) NOT NULL CHECK (daily_rate > 0)
);

CREATE TABLE rentals (
    rental_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id     integer   NOT NULL REFERENCES items (item_id),
    customer_id integer   NOT NULL REFERENCES customers (customer_id),
    -- Half-open [first rental day, day the item comes back), so "touching" rentals (one ends the day the next
    -- starts) do not overlap. The check refuses empty ranges. For daterange the [) form is also what PostgreSQL
    -- stores for every input (it rewrites '[a,b]' as '[a,b+1)'), so the two bound tests only state the rule;
    -- they cannot fail. See the closed-range case in 004_constraint_demo.sql.
    during      daterange NOT NULL
        CHECK (NOT isempty(during) AND lower_inc(during) AND NOT upper_inc(during))
);

-- Foreign keys index the parent side only; the child columns need their own indexes.
-- History of one customer, newest or oldest first.
CREATE INDEX rentals_customer ON rentals (customer_id, lower(during));
-- Returns due on a given day.
CREATE INDEX rentals_return_day ON rentals (upper(during));

COMMENT ON TABLE rentals IS 'One row per rental of one item for a half-open date range.';
COMMENT ON COLUMN rentals.during IS 'Half-open daterange [first rental day, return day). The return day is free again.';
